// Copies compiled ABIs and creation bytecode into the web app as typed `as const` modules.
// Run after `npx hardhat compile` (and `node vendor/build.js` for the vendored Pons contracts):
//   node scripts/export-abi.js
const fs = require("fs");
const path = require("path");

const hardhat = (name) => require(path.join(__dirname, "..", "artifacts", "contracts", `${name}.sol`, `${name}.json`));
const vendor = (name) => require(path.join(__dirname, "..", "vendor", "out", `${name}.json`));

// PonsEarn's own contracts, and the Pons v2 / Uniswap v4 ABIs the app reads and writes (the real
// ones, from the verified sources in contracts/vendor).
const abis = {
  launcherAbi: hardhat("PonsEarnLauncher").abi,
  feeVaultAbi: hardhat("FeeVault").abi,
  feeSplitterAbi: hardhat("FeeSplitter").abi,
  routerAbi: hardhat("PonsEarnRouter").abi,
  ponsFactoryAbi: vendor("PonsV2LaunchFactory").abi,
  ponsCurveAbi: vendor("PonsV2BondingCurve").abi,
  ponsTokenAbi: vendor("PonsV2LauncherToken").abi,
  ponsHookAbi: vendor("PonsV2MemeHook").abi,
  ponsEscrowAbi: vendor("PonsV2FeeEscrow").abi,
  ponsVaultAbi: vendor("PonsV2BuybackVault").abi,
  ponsLockerAbi: vendor("PonsV2LaunchLocker").abi,
  ponsExecutorAbi: vendor("PonsV2GraduationExecutor").abi,
  ponsDeployerAbi: vendor("PonsV2LaunchDeployer").abi,
  poolManagerAbi: vendor("PoolManager").abi.filter((item) => item.type === "event" || item.name === "extsload"),
};

let src = "// Generated by contracts/scripts/export-abi.js. Do not edit by hand.\n";
for (const [name, abi] of Object.entries(abis)) {
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
const out = path.join(__dirname, "..", "..", "src", "lib", "abi.ts");
fs.writeFileSync(out, src);
console.log(`Wrote ${out}`);

// Creation bytecode for /setup, where the owner's wallet deploys PonsEarn (both networks) and, on
// testnet, PonsEarn's copy of Pons v2. Loaded only when /setup deploys.
const bytecodes = {
  feeVault: hardhat("FeeVault").bytecode,
  launcher: hardhat("PonsEarnLauncher").bytecode,
  ponsFeeEscrow: vendor("PonsV2FeeEscrow").bytecode,
  ponsMemeHook: vendor("PonsV2MemeHook").bytecode,
  ponsBuybackVault: vendor("PonsV2BuybackVault").bytecode,
  ponsLaunchLocker: vendor("PonsV2LaunchLocker").bytecode,
  ponsLaunchFactory: vendor("PonsV2LaunchFactory").bytecode,
  ponsGraduationExecutor: vendor("PonsV2GraduationExecutor").bytecode,
  ponsLaunchDeployer: vendor("PonsV2LaunchDeployer").bytecode,
};
let bc = "// Generated by contracts/scripts/export-abi.js. Do not edit by hand.\n\nexport const bytecode = {\n";
for (const [name, code] of Object.entries(bytecodes)) bc += `  ${name}: "${code}",\n`;
bc += "} as const;\n";
const bytecodeOut = path.join(__dirname, "..", "..", "src", "lib", "bytecode.ts");
fs.writeFileSync(bytecodeOut, bc);
console.log(`Wrote ${bytecodeOut}`);

// Copies compiled ABIs into the web app as typed `as const` modules.
// Run after `npx hardhat compile`: node scripts/export-abi.js
const fs = require("fs");
const path = require("path");

const out = path.join(__dirname, "..", "..", "src", "lib", "abi.ts");
const contracts = { launchpadAbi: "SplitLaunchpad", feeVaultAbi: "FeeVault", splitTokenAbi: "SplitToken" };

let src = "// Generated by contracts/scripts/export-abi.js. Do not edit by hand.\n";
for (const [name, contract] of Object.entries(contracts)) {
  const file = path.join(__dirname, "..", "artifacts", "contracts", `${contract}.sol`, `${contract}.json`);
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log(`Wrote ${out}`);

// Creation bytecode for the in-app setup page, which deploys from the web server.
const bytecodeOut = path.join(__dirname, "..", "..", "src", "lib", "bytecode.ts");
let bc = '// Generated by contracts/scripts/export-abi.js. Do not edit by hand.\nimport "server-only";\n';
for (const [name, contract] of Object.entries({ feeVaultBytecode: "FeeVault", launchpadBytecode: "SplitLaunchpad" })) {
  const file = path.join(__dirname, "..", "artifacts", "contracts", `${contract}.sol`, `${contract}.json`);
  const { bytecode } = JSON.parse(fs.readFileSync(file, "utf8"));
  bc += `\nexport const ${name} = "${bytecode}" as const;\n`;
}
fs.writeFileSync(bytecodeOut, bc);
console.log(`Wrote ${bytecodeOut}`);

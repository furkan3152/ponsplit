// Copies compiled ABIs into the web app as typed `as const` modules.
// Run after `npx hardhat compile`: node scripts/export-abi.js
const fs = require("fs");
const path = require("path");

const out = path.join(__dirname, "..", "..", "src", "lib", "abi.ts");
const contracts = { launchpadAbi: "SplitLaunchpad", feeVaultAbi: "FeeVault", splitTokenAbi: "SplitToken" };

let src = "// Generated by contracts/scripts/export-abi.js. Do not edit by hand.\n";
for (const [name, contract] of Object.entries(contracts)) {
  const file = path.join(__dirname, "..", "artifacts", "contracts", `${contract}.sol`, `${contract}.json`);
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log(`Wrote ${out}`);

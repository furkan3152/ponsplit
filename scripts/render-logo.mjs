// Renders the brand mark (src/components/art/Logo.tsx) to static SVG files with literal colors,
// for places that can't use the app's CSS variables: the favicon, the home-screen icon and
// share cards.   node scripts/render-logo.mjs
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { transform } from "sucrase";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "node_modules", ".cache", "logo");
mkdirSync(out, { recursive: true });
for (const f of ["Logo", "CreatorReel"]) {
  const src = readFileSync(join(root, "src/components/art", `${f}.tsx`), "utf8");
  const { code } = transform(src, { transforms: ["typescript", "jsx", "imports"], jsxRuntime: "automatic", production: true });
  writeFileSync(join(out, `${f}.cjs`), code.replace(/require\(['"]\.\/(\w+)['"]\)/g, 'require("./$1.cjs")'));
}
const { createRequire } = await import("module");
const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const { LogoMark } = require(join(out, "Logo.cjs"));
const { CreatorReel } = require(join(out, "CreatorReel.cjs"));

const colors = { lime: "#4df3e0", coral: "#ff5a75" };
let svg = renderToStaticMarkup(React.createElement(LogoMark, { size: 64 }));
svg = svg.replace(/var\(--([\w-]+)(?:,\s*[^)]+)?\)/g, (m, name) => colors[name] ?? m);
if (svg.includes("var(")) throw new Error(`unresolved color in ${svg}`);
svg = svg.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ').replace(/ aria-hidden="true"| focusable="false"/g, "");
writeFileSync(join(root, "public/logo.svg"), svg + "\n");
writeFileSync(join(root, "src/app/icon.svg"), svg + "\n");
// Server-rendered images read the logo from the bundle: Vercel functions don't carry public/.
writeFileSync(
  join(root, "src/lib/logo-svg.ts"),
  `// Generated by scripts/render-logo.mjs: the logo for images rendered on the server.\nexport const LOGO_DATA_URL = ${JSON.stringify("data:image/svg+xml;base64," + Buffer.from(svg + "\n").toString("base64"))};\n`
);
console.log(svg.length, "bytes");

const artColors = { ...colors, ink: "#f3f0e8", paper: "#0b0c0f", card: "#141619" };
let art = renderToStaticMarkup(React.createElement(CreatorReel));
art = art.replace(/var\(--([\w-]+)(?:,\s*[^)]+)?\)/g, (match, name) => artColors[name] ?? match);
if (art.includes("var(")) throw new Error("Unresolved creator illustration color");
writeFileSync(join(root, "public/creator-reel.svg"), art + "\n");
writeFileSync(join(root, "src/lib/creator-reel-svg.ts"), `// Generated original artwork for server-rendered share images.\nexport const CREATOR_REEL_DATA_URL = ${JSON.stringify("data:image/svg+xml;base64," + Buffer.from(art).toString("base64"))};\n`);
